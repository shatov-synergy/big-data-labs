"""Аудит Задачи 2, Проход 7: трассировка PDF<->расчёты, структура,
оговорки. Числа-эталоны — из summary.rds/CSV (дамп выше), PDF — pdftotext."""
import re
import subprocess

PDF = "labs/lab-04/output/Laboratornyiy praktikum 4_Задача 2_отчет.pdf"
txt = subprocess.run(["pdftotext", PDF, "-"], capture_output=True, text=True).stdout
t = re.sub(r"\s+", " ", txt)

def has(name, pat):
    ok = re.search(pat, t) is not None
    print(("OK  " if ok else "НЕТ "), name)
    return ok

print("=== 1. Трассировка чисел: корреляции и погода ===")
has("частная корр. цены −0,479/−0,48", r"−0\.479|−0\.48|0\.479|0\.48")
has("частная корр. t_mean −0,007/≈0", r"0\.007|−0\.007")
has("осадки: сырая −0,130/−0,13", r"0\.13")
has("дождливых дней 648", r"648")
has("дождь −3,9% / −30 шт.", r"3,9")
has("t-тест p 0,0006", r"0\.0006")
has("согласованность темп. 0,981/0,98", r"0\.981|0\.98")
has("ветер частная 0,207/0,21", r"0\.207|0\.21")

print("\n=== 2. Цена ===")
has("Пирсон цены −0,277/−0,28", r"0\.277|−0\.28")
has("эластичность −0,286/−0,29", r"0\.286|−0\.29")

print("\n=== 3. Макро ===")
has("овощи 80,1 → 112,5 (или 80→112)", r"112")
has("фрукты 39,9 → 80,3 (или 40→80)", r"80")
has("cor(FRS,VGS) 0,913/0,91", r"0\.913|0\.91")
has("годы 1992–2021", r"1992")
has("тренды 1,74 и 1,62", r"1\.74|1\.62")

print("\n=== 4. Статистика ряда ===")
has("1096 дней", r"1096|1 096")
has("среднее 756/755,6", r"756|755")
has("цена средняя 106,6/107", r"106|107")
has("пятница макс 782", r"782")

print("\n=== 5. Структура отчёта (по заданию З2) ===")
blocks = [
    ("ВВЕДЕНИЕ", "ВВЕДЕНИЕ"), ("теория (раздел 1)", "Теоретические основы"),
    ("бизнес-специфика", "Бизнес-специфика"),
    ("EDA: ряд+train/test", "рисунок 1"), ("недельный профиль", "рисунок 2"),
    ("таблица параметров+обоснование", "Таблица 4"),
    ("таблица метрик", "Таблица 7"),
    ("график сравнения", "рисунок 7"),
    ("компоненты лучшего Prophet", "рисунок 9"),
    ("диагностика победителя", "рисунок 11"),
    ("вывод о модели (бизнес)", "ВЫВОДЫ"),
]
for name, pat in blocks:
    has(name, re.escape(pat))

print("\n=== 6. Оговорки ===")
has("подбор по test оговорён?", r"подбор.*test|по тестовом|оптимистичн")
has("фактическая будущая погода оговорена?", r"фактическ\w+ (будущ|значени)|ретроспективн|ex post|условн\w+ сценар")
has("«на данном тестовом периоде»?", r"на данном тестовом периоде|данном тестовом окне")
has("AI4Research и ссылка arXiv", r"arXiv:2507\.01903|2507\.01903")
has("источник погоды (Open-Meteo)", r"Open-Meteo")
has("источник макро (НЦСЭД/ОЭСР)", r"НЦСЭД|ОЭСР")
has("NSedc-датасет назван (DF_HEALTH_LVNG)", r"DF_HEALTH_LVNG|HEALTH_LVNG")

print("\n=== 7. Титул ===")
has("преподаватель вписан (Дзизинская)", r"Дзизинская")
has("группа ДМЭ-101цэии", r"ДМЭ-101")
has("МОСКВА 2026", r"МОСКВА 2026")

print("\n=== 8. Объём ===")
pages = int(subprocess.run(["pdfinfo", PDF], capture_output=True, text=True)
            .stdout.split("Pages:")[1].split()[0])
print("страниц:", pages, "(задание: 5–8)")
